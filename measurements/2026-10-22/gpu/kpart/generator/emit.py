"""emit.py -- ax-13 (wave 16).  Turns searched circuits (search/circ/*.drop.txt) into drop-in code for the SAME
matrices that executorch and Dao ship, checks every circuit exactly, and writes:

  out/fast_hadamard_transform_special.h       executorch drop-in: hadamard_mult_{12,20,28,40}_strided<T> (scalar,
                                              same names and signatures as the generated header) + 4-lane float
                                              kernels ax13_hk<K>_cse_v4 and the column drivers used by the patch
  out/dao_fast_hadamard_transform_special.h   Dao drop-in: __device__ hadamard_mult_thread_{12,20,28,40}(float x[K])
  out/counts.md                               adds, negations, depth per kernel

The 40-point matrix both libraries ship is [[A, A], [A, -A]] (checked here), so its circuit is 40 butterflies
followed by A's circuit on each half.
"""
import sys, os, heapq, random
H = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, H)
from cse_lib import check_exact, depth

def rd_mat(p):
    rows = [l.strip() for l in open(p) if l.strip() and l.strip()[0] in '+-']
    return [[1 if c == '+' else -1 for c in r] for r in rows]

def rd_circ(p):
    defs, rows = [], {}
    for l in open(p):
        f = l.split()
        if not f or f[0] == '#': continue
        if f[0] == 'd': defs.append(tuple(int(v) for v in f[1:5]))
        elif f[0] == 'o':
            i = int(f[1]); rows[i] = {int(f[k]): int(f[k + 1]) for k in range(2, len(f), 2)}
    return defs, [rows[i] for i in range(len(rows))]

def kron2(defsA, rowsA, KA):
    """circuit for [[A, A], [A, -A]] (2KA inputs) from A's circuit."""
    K = 2 * KA; nxt = K; defs = []
    u = {}; w = {}
    for j in range(KA):
        u[j] = nxt; defs.append((nxt, j, j + KA, 1)); nxt += 1
    for j in range(KA):
        w[j] = nxt; defs.append((nxt, j, j + KA, -1)); nxt += 1
    rows = []
    for inmap in (u, w):
        m = dict(inmap)
        for t, a, b, s in defsA:
            m[t] = nxt; defs.append((nxt, m[a], m[b], s)); nxt += 1
        rows += [{m[v]: c for v, c in r.items()} for r in rowsA]
    return defs, rows

def tree(terms, dep):
    h = [(dep(n), i, (c, str(n))) for i, (c, n) in enumerate(terms)]
    heapq.heapify(h); k = len(h)
    while len(h) > 1:
        d1, _, (s1, e1) = heapq.heappop(h); d2, _, (s2, e2) = heapq.heappop(h)
        if s1 < 0 and s2 > 0: (s1, e1), (s2, e2) = (s2, e2), (s1, e1)
        heapq.heappush(h, (max(d1, d2) + 1, k, (s1, '(%s %s %s)' % (e1, '+' if s1 == s2 else '-', e2)))); k += 1
    s, e = h[0][2]
    return (e if s > 0 else '(-%s)' % e), (0 if s > 0 else 1)

def build(K, M, defs, rows, name_in):
    assert check_exact(M, defs, rows, random.Random(K)), K
    adds = len(defs) + sum(len(r) - 1 for r in rows)
    dmap = {}
    for t, a, b, s in defs: dmap[t] = max(dmap.get(a, 0), dmap.get(b, 0)) + 1
    dep = lambda n: dmap.get(n, 0)
    outs, negs = [], 0
    for r in rows:
        e, ng = tree([(c, w) for w, c in sorted(r.items())], dep); negs += ng; outs.append(e)
    return dict(K=K, adds=adds, negs=negs, depth=depth(defs, rows), defs=defs, outs=outs, name=name_in)

def body(c, T, vname, load, store):
    L = []
    L += ['  %s %s = %s;' % (T, vname(j), load(j)) for j in range(c['K'])]
    L += ['  %s %s = %s %s %s;' % (T, vname(t), vname(a), '+' if s > 0 else '-', vname(b)) for t, a, b, s in c['defs']]
    rep = lambda e: __import__('re').sub(r'(?<![\w\]])(\d+)(?![\w\[])', lambda m: vname(int(m.group(1))), e)
    L += ['  %s o%d = %s;' % (T, i, rep(e)) for i, e in enumerate(c['outs'])]
    L += ['  %s' % store(i) for i in range(c['K'])]
    return L

def main():
    S = os.path.join(H, 'search')
    os.makedirs(os.path.join(H, 'out'), exist_ok=True)
    jobs = {}
    for K in (12, 20, 28):
        M = rd_mat(os.path.join(S, 'mats/et_%d.txt' % K)); d, r = rd_circ(os.path.join(S, 'circ/et_%d.drop.txt' % K))
        jobs[('et', K)] = build(K, M, d, r, 'executorch had_%d' % K)
    M40 = rd_mat(os.path.join(S, 'mats/et_40.txt'))
    assert all(M40[i][j] == M40[i][j + 20] for i in range(20) for j in range(20))
    assert all(M40[i + 20][j] == -M40[i + 20][j + 20] == M40[i][j] for i in range(20) for j in range(20))
    dA, rA = rd_circ(os.path.join(S, 'circ/et_40_A20.drop.txt'))
    d, r = kron2(dA, rA, 20)
    jobs[('et', 40)] = build(40, M40, d, r, 'had_40_tpal = [[A,A],[A,-A]]')
    M12p = rd_mat(os.path.join(S, 'mats/dao_had_12_paley.txt')); d, r = rd_circ(os.path.join(S, 'circ/dao_had_12_paley.drop.txt'))
    jobs[('dao', 12)] = build(12, M12p, d, r, 'had_12_paley')
    for K in (20, 28, 40): jobs[('dao', K)] = jobs[('et', K)]
    v = lambda n: 'v%d' % n
    # executorch drop-in
    E = ['// @generated by ax-13 emit.py: shared-subexpression circuits for the SAME matrices as special_hadamard_code_gen.py',
         '// (each checked exactly on all unit vectors and 50 random integer vectors before writing).', '', '#pragma once', '#include <cstring>', '']
    for K in (12, 20, 28, 40):
        c = jobs[('et', K)]
        E.append('// %s: %d additions (+%d negations), depth %d; the dense form has %d' % (c['name'], c['adds'], c['negs'], c['depth'], K * (K - 1)))
        E.append('template <typename T>\nvoid hadamard_mult_%d_strided(T* input, int stride) {' % K)
        E += body(c, 'T', v, lambda j: 'input[%d * stride]' % j, lambda i: 'input[%d * stride] = o%d;' % (i, i))
        E.append('}\n')
    E.append('#if defined(__clang__) || defined(__GNUC__)')
    E.append('typedef float et_hk_vf4 __attribute__((vector_size(16), aligned(4)));')
    for K in (12, 20, 28, 40):
        c = jobs[('et', K)]
        E.append('// 4 adjacent columns at once (4-lane float vectors; NEON on arm64, SSE on x86-64)')
        E.append('inline void hadamard_mult_%d_strided_x4(float* p, int stride) {' % K)
        E += body(c, 'et_hk_vf4', v, lambda j: '*(const et_hk_vf4*)(p + %d * stride)' % j, lambda i: '*(et_hk_vf4*)(p + %d * stride) = o%d;' % (i, i))
        E.append('}')
        E.append('// the whole K-part of a (%d x vec_size) row-major block: columns in groups of 4, then the scalar tail' % K)
        E.append('inline void hadamard_mult_%d_columns(float* vec, int vec_size) {' % K)
        E.append('  int ii = 0;')
        E.append('  for (; ii + 4 <= vec_size; ii += 4) hadamard_mult_%d_strided_x4(vec + ii, vec_size);' % K)
        E.append('  for (; ii < vec_size; ++ii) hadamard_mult_%d_strided(vec + ii, vec_size);' % K)
        E.append('}\n')
    E.append('#endif')
    open(os.path.join(H, 'out/fast_hadamard_transform_special.h'), 'w').write('\n'.join(E) + '\n')
    # Dao drop-in
    D = ['', '#pragma once', '', '// @generated by ax-13 emit.py: shared-subexpression circuits for the SAME matrices as code_gen.py',
         '// (had_12_paley, had_20_will, had_28_will, had_40_tpal), each checked exactly before writing.', '']
    for K in (12, 20, 28, 40):
        c = jobs[('dao', K)]
        D.append('__device__ __forceinline__ void hadamard_mult_thread_%d(float x[%d]) {' % (K, K))
        D.append('  // %s: %d additions (+%d negations), depth %d; dense %d' % (c['name'], c['adds'], c['negs'], c['depth'], K * (K - 1)))
        D += body(c, 'float', v, lambda j: 'x[%d]' % j, lambda i: 'x[%d] = o%d;' % (i, i))
        D.append('}\n')
    open(os.path.join(H, 'out/dao_fast_hadamard_transform_special.h'), 'w').write('\n'.join(D) + '\n')
    C = ['| library | K | matrix | dense adds | circuit adds | adds per point dense -> circuit | negations | depth |', '|---|---|---|---|---|---|---|---|']
    for (lib, K), c in sorted(jobs.items()):
        C.append('| %s | %d | %s | %d | %d | %.2f -> %.2f | %d | %d |' % (lib, K, c['name'], K * (K - 1), c['adds'], K - 1, c['adds'] / K, c['negs'], c['depth']))
    open(os.path.join(H, 'out/counts.md'), 'w').write('\n'.join(C) + '\n')
    print('\n'.join(C))

if __name__ == '__main__':
    main()
