#!/usr/bin/env python3
"""gen_cuda.py -- circuit files -> CUDA device functions (22 Oct 2026).  One instruction per circuit line:
u +- v -> FADD; u +- c*v and c*u - v -> one FFMA (NVIDIA FFMA takes a negated operand and an immediate for free);
c*u -> FMUL.  Usage: gen_cuda.py NAME FILE [NAME FILE]... > kernels_cuda.h   (FILE may be textbookN)."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_kernels import load  # noqa: E402


def emit(name, spec):
    n, gates, outs = load(spec)
    L = [f'/* {name}: {n} points, {len(gates)} lines, from {os.path.basename(spec)} */',
         f'__device__ __forceinline__ void {name}(float *v) {{',
         '  ' + ' '.join(f'const float x{i} = v[{i}];' for i in range(n))]
    for w, terms in gates:
        if len(terms) == 1:
            c, u = terms[0]
            e = f'{float(c)!r}f * {u}'
        else:
            (c1, u), (c2, v) = terms
            if abs(c1) != 1:
                (c1, u), (c2, v) = (c2, v), (c1, u)
            if abs(c2) == 1:
                e = {(1, 1): f'{u} + {v}', (1, -1): f'{u} - {v}', (-1, 1): f'{v} - {u}', (-1, -1): f'-({u} + {v})'}[(int(c1), int(c2))]
            else:
                e = f'__fmaf_rn({v}, {float(c2)!r}f, {"" if c1 > 0 else "-"}{u})'
        L.append(f'  const float {w} = {e};')
    L += [f'  v[{j}] = {o};' for j, o in enumerate(outs)] + ['}', '']
    return '\n'.join(L)


a = sys.argv[1:]
print('/* generated by gen_cuda.py (22 Oct 2026); do not edit */')
for nm, sp in zip(a[0::2], a[1::2]):
    print(emit(nm, sp))
