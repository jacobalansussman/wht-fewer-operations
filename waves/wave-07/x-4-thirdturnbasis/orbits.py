# x-4: the split in the half-transformed basis. Exact (whole numbers).
# address x: pair i has bits c_i (position 2i) and b_i (position 2i+1). Q = c.b ; F = transform over c only: (F v)(a,b) = sum_c (-1)^(a.c) v(c,b).
# Claims checked: F D = P_D F with P_D the relabelling (a,b)->(a+b,b);  F H = s P_X F with P_X the exchange (a,b)->(b,a);
# so F R = P_R F with (a,b)->(b,a+b) or its inverse. Then: orbits, their counts, and the supports of the pulled-back vectors.
def pop(v): return bin(v).count('1')
def run(n):
    k = 2*n; N = 1 << k; s = 1 << n
    def split(x):
        c = sum(((x >> (2*i)) & 1) << i for i in range(n)); b = sum(((x >> (2*i+1)) & 1) << i for i in range(n)); return c, b
    def join(c, b): return sum((((c >> i) & 1) << (2*i)) | (((b >> i) & 1) << (2*i+1)) for i in range(n))
    def Q(x): c, b = split(x); return pop(c & b) & 1
    def Bf(x, y): return (Q(x ^ y) + Q(x) + Q(y)) & 1
    H = [[(-1)**Bf(x, y) for y in range(N)] for x in range(N)]
    d = [(-1)**Q(x) for x in range(N)]
    F = [[0]*N for _ in range(N)]
    for x in range(N):
        c, b = split(x)
        for a in range(s): F[join(a, b)][x] = (-1)**pop(a & c)
    def mul(A, Bm):
        Bt = list(zip(*Bm)); return [[sum(p*q for p, q in zip(r, col)) for col in Bt] for r in A]
    FD = [[F[i][j]*d[j] for j in range(N)] for i in range(N)]
    FH = mul(F, H)
    # P_D F : row (a,b) of result = row (a+b, b) of F  (or the inverse; the relabelling is an involution)
    okD = all(FD[join(a, b)] == F[join(a ^ b, b)] for a in range(s) for b in range(s))
    okH = all(FH[join(a, b)] == [s*v for v in F[join(b, a)]] for a in range(s) for b in range(s))
    print('N=%d: F D F^-1 is the relabelling (a,b)->(a+b,b): %s ; F H F^-1 = s x the exchange (a,b)->(b,a): %s' % (N, okD, okH))
    # orbits of the group generated by the two relabellings
    seen = set(); sizes = {}
    orbs = []
    for a in range(s):
        for b in range(s):
            if (a, b) in seen: continue
            orb = {(a, b)}; frontier = [(a, b)]
            while frontier:
                (u, v) = frontier.pop()
                for w in ((u ^ v, v), (v, u)):
                    if w not in orb: orb.add(w); frontier.append(w)
            seen |= orb; orbs.append(sorted(orb)); sizes[len(orb)] = sizes.get(len(orb), 0) + 1
    print('   orbits by size: %s ; number of orbits = %d, formula (s+1)(s+2)/6 = %d ; orbits of six = %d, formula (s-1)(s-2)/6 = %d ; fixed space of R = their sum = %d = (N+2)/3 = %d'
          % (sizes, len(orbs), (s+1)*(s+2)//6, sizes.get(6, 0), (s-1)*(s-2)//6, len(orbs) + sizes.get(6, 0), (N+2)//3))
    # pull back by F^-1 = F^T / s (F is symmetric up to the labelling; use F^T): vector u on (a,b) -> F^T u
    def pull(u):
        return [sum(F[i][x]*u[i] for i in range(N)) for x in range(N)]
    sup_plus = set(); sup_minus = set(); ok_plus = ok_minus = True
    for orb in orbs:
        u = [0]*N
        for (a, b) in orb: u[join(a, b)] = 1
        v = pull(u)
        ok_plus &= all(sum(H[x][y]*v[y] for y in range(N)) == s*v[x] for x in range(N)) and all(v[x] == 0 or d[x] == 1 for x in range(N))
        sup_plus.add(sum(1 for t in v if t != 0))
        if len(orb) == 6:
            # alternating sum: sign = parity of the group element; walk the orbit with the two generators (each is odd)
            a, b = orb[0]; sign = {(a, b): 1}; frontier = [(a, b)]
            while frontier:
                (p, q) = frontier.pop()
                for w in ((p ^ q, q), (q, p)):
                    if w not in sign: sign[w] = -sign[(p, q)]; frontier.append(w)
            u = [0]*N
            for (p, q), sg in sign.items(): u[join(p, q)] = sg
            v = pull(u)
            ok_minus &= all(sum(H[x][y]*v[y] for y in range(N)) == -s*v[x] for x in range(N)) and all(v[x] == 0 or d[x] == -1 for x in range(N))
            sup_minus.add(sum(1 for t in v if t != 0))
    print('   pulled-back orbit sums: all fixed and on Q=0: %s, supports %s ; pulled-back alternating sums of the 6-orbits: all with H v = -s v and on Q=1: %s, supports %s (3s/2 = %d)'
          % (ok_plus, sorted(sup_plus), ok_minus, sorted(sup_minus), 3*s//2))
for n in (1, 2, 3): run(n)
