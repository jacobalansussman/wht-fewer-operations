#!/usr/bin/env python3
"""lp_sym.py [ab-1-fewerblocks]  The same linear program as lp.py, reduced by symmetry so that block sizes 5 and 6 fit.
Symmetry used: the address maps g with g g^T = 1 generated by the exchanges of two address bits and (m >= 4) the map
x -> x + (x.u) u with u = 1111 on the first four bits.  They keep I, the rank of a form and the pairing <Q,B>
(Q -> Q(g^-1 .), B -> g B g^T), so an optimal solution may be taken constant on orbits of forms, and one inequality per
orbit of characters suffices.  Any subgroup of the symmetries gives the same optimum.  FLOATS (HiGHS)."""
import sys, numpy as np, time
from scipy.optimize import linprog
m = int(sys.argv[1]); t0 = time.time()
idx = [(i, j) for i in range(m) for j in range(i, m)]; pos = {p: t for t, p in enumerate(idx)}; nb = len(idx); NN = 1 << nb
def matmul(A, B): return [[sum(A[i][k] & B[k][j] for k in range(m)) & 1 for j in range(m)] for i in range(m)]
def tr(A): return [[A[j][i] for j in range(m)] for i in range(m)]
def code_of_sym(M): return sum(1 << pos[(i, j)] for (i, j) in idx if M[i][j])
def gens():
    out = []
    for a in range(m - 1):
        g = [[int(i == j) for j in range(m)] for i in range(m)]; g[a], g[a + 1] = g[a + 1], g[a]; out.append(g)
    if m >= 4:
        g = [[int(i == j) ^ int(i < 4 and j < 4) for j in range(m)] for i in range(m)]; out.append(g)
    for g in out: assert matmul(g, tr(g)) == [[int(i == j) for j in range(m)] for i in range(m)]
    return out
def lin_action_B(g):
    cols = []
    for (i, j) in idx:
        E = [[0] * m for _ in range(m)]; E[i][j] = E[j][i] = 1
        cols.append(code_of_sym(matmul(matmul(g, E), tr(g))))
    return cols
def lin_action_Q(g):
    # Q -> Q(g^-1 .) ; g is its own inverse for the generators used (exchanges and the map with u.u = 0)
    assert matmul(g, g) == [[int(i == j) for j in range(m)] for i in range(m)]
    cols = []
    for (i, j) in idx:
        # monomial z_i z_j composed with g: (g z)_i (g z)_j = sum_{k,l} g_ik g_jl z_k z_l ; z_k^2 = z_k
        c = 0
        for k in range(m):
            for l in range(m):
                if g[i][k] & g[j][l]: c ^= 1 << pos[(min(k, l), max(k, l))]
        cols.append(c)
    return cols
def apply(cols, codes):
    out = np.zeros_like(codes)
    for t in range(nb): out ^= np.where((codes >> t) & 1 == 1, cols[t], 0).astype(codes.dtype)
    return out
codes = np.arange(NN, dtype=np.int64)
def orbits(actions):
    lab = codes.copy()
    perms = [apply(c, codes) for c in actions]
    while True:
        old = lab.copy()
        for p in perms:
            lab = np.minimum(lab, lab[p]); 
        for _ in range(3): lab = lab[lab]
        if (lab == old).all(): break
    return lab
G = gens()
labB = orbits([lin_action_B(g) for g in G]); labQ = orbits([lin_action_Q(g) for g in G])
# ranks and the alternating test for representatives of B-orbits
def rank_code(code):
    rows = [0] * m
    for t, (i, j) in enumerate(idx):
        if code >> t & 1: rows[i] |= 1 << j; rows[j] |= 1 << i
    rk = 0
    for c in range(m):
        pv = next((i for i in range(rk, m) if rows[i] >> c & 1), None)
        if pv is None: continue
        rows[rk], rows[pv] = rows[pv], rows[rk]
        for i in range(m):
            if i != rk and rows[i] >> c & 1: rows[i] ^= rows[rk]
        rk += 1
    return rk
Icode = sum(1 << pos[(i, i)] for i in range(m))
repsB = np.unique(labB); repsQ = np.unique(labQ)
parity = lambda x: np.bitwise_count(x.astype(np.uint64)).astype(np.int64) & 1
Bok = [(int(b), rank_code(int(b))) for b in repsB if (int(b) & Icode) and rank_code(int(b)) <= m - 1]
Qok = [int(q) for q in repsQ if bin(int(q) & Icode).count("1") & 1]
sizeB = {b: int((labB == b).sum()) for b, _ in Bok}
print("m = %d : %d forms in %d orbits ; block forms: %d orbits ; characters with <Q,I> = 1: %d orbits   [%.0f s]" % (m, NN, len(repsB), len(Bok), len(Qok), time.time() - t0), flush=True)
# counts: for Q-rep q and B-orbit O: number of B in O with <q,B> = 1
orbit_index = {b: k for k, (b, _) in enumerate(Bok)}
A = np.zeros((len(Qok), len(Bok)))
members = {b: codes[labB == b] for b, _ in Bok}
for a, q in enumerate(Qok):
    for b, _ in Bok: A[a, orbit_index[b]] = parity(members[b] & q).sum()
rk = np.array([r for _, r in Bok], dtype=float); sz = np.array([sizeB[b] for b, _ in Bok], dtype=float)
def solve(cost): return linprog(cost * sz, A_ub=-A, b_ub=-np.ones(len(Qok)), bounds=(0, None), method="highs")
r1 = solve(rk); r0 = solve(np.ones(len(Bok)))
print("   least moves per live array (LP):  %.6f   (plain schedule: %d ; ratio %.4f)" % (r1.fun, m, r1.fun / m))
print("   least blocks per live array (LP): %.6f   (plain schedule: 2)" % r0.fun)
for z in (1.0, 0.95, 0.9, 0.8, 0.7, 0.5): print("      z = %.2f : least price per live array %.6f" % (z, solve((rk / m) ** z).fun))
lo, hi = 0.0, 1.0
for _ in range(40):
    mid = (lo + hi) / 2
    if solve((rk / m) ** mid).fun < 1: hi = mid
    else: lo = mid
print("   the LP price reaches 1 at z = %.6f : the character inequalities allow no saving above %.6f in the sub-game at block size %d" % (hi, 1 - hi, m))
r = solve((rk / m) ** (hi + 1e-6)); x = r.x
print("   minimising fractional unit just above that z, by rank: blocks per array %s ; total blocks %.4f ; moves %.4f"
      % ({int(k): round(float((x * sz)[rk == k].sum()), 4) for k in sorted(set(rk)) if (x * sz)[rk == k].sum() > 1e-9}, (x * sz).sum(), (x * sz * rk).sum()))
x1 = r1.x
print("   minimising fractional unit for moves, by rank: %s" % ({int(k): round(float((x1 * sz)[rk == k].sum()), 4) for k in sorted(set(rk)) if (x1 * sz)[rk == k].sum() > 1e-9}))
print("   [%.0f s]" % (time.time() - t0))
