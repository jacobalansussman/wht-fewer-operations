#!/usr/bin/env python3
"""refl.py [ab-1-fewerblocks]  FLOATS: a numerical hunt, not a proof and not a replay.
Sub-game without address maps, phase letters or shift letters, blocks of rank 1 (single moves).  [derived tonight]
A word with moves z_1..z_B is a unit for W live arrays and S scratch arrays exactly when there are matrices
P_j = u_j v_j^T (v_j.u_j = 1) of size W+S with, for EVERY character psi of the commutative group generated by the moves,
        prod_j (1 + (psi(z_j) - 1) P_j)  maps (x, 0) to (psi(kernel) x, anything).
Characters: psi(z) = i^(sum a_i z_i + 2 sum_{i<j} b_ij z_i z_j), a_i in Z/4, b_ij in Z/2; psi(kernel) = i^(sum a_i).
mode 'pm' uses only the characters with a_i in {0, 2} (values +-1; these give the linear program of lp.py); mode 'all' uses all.
usage: refl.py m W S seq restarts seed mode      seq = 'all' (every non-zero direction once, random order) or 'plain' or a comma list"""
import sys, itertools, numpy as np, time
from scipy.optimize import least_squares
m, W, S = int(sys.argv[1]), int(sys.argv[2]), int(sys.argv[3]); seqs = sys.argv[4]; restarts = int(sys.argv[5]); rng = np.random.default_rng(int(sys.argv[6])); mode = sys.argv[7]
D = W + S
pairs = [(i, j) for i in range(m) for j in range(i + 1, m)]
def chars(mode):
    out = []
    for a in itertools.product(range(0, 4, 2) if mode == "pm" else range(4), repeat=m):
        for b in itertools.product(range(2), repeat=len(pairs)): out.append((a, b))
    return out
CH = {"pm": chars("pm"), "all": chars("all")}
def table(seq, mode):
    ch = CH[mode]; beta = np.zeros((len(ch), len(seq)), dtype=complex); tgt = np.zeros(len(ch), dtype=complex)
    for c, (a, b) in enumerate(ch):
        tgt[c] = 1j ** (sum(a) % 4)
        for j, z in enumerate(seq):
            e = sum(a[i] * (z >> i & 1) for i in range(m)) + 2 * sum(bb * (z >> i & 1) * (z >> jj & 1) for bb, (i, jj) in zip(b, pairs))
            beta[c, j] = 1j ** (e % 4)
    return beta, tgt
def resid(par, beta, tgt):
    B = beta.shape[1]; U = par[:B * D].reshape(B, D); V = par[B * D:].reshape(B, D)
    M = np.broadcast_to(np.eye(D, dtype=complex)[:, :W], (beta.shape[0], D, W)).copy()
    for j in range(B):
        u = U[j] / (V[j] @ U[j])
        w = np.einsum("d,cdk->ck", V[j], M)
        M += ((beta[:, j] - 1)[:, None, None]) * u[None, :, None] * w[:, None, :]
    R = M[:, :W, :] - tgt[:, None, None] * np.eye(W)[None]
    return np.concatenate([R.real.ravel(), R.imag.ravel()])
def run(seq, mode, tries, label):
    beta, tgt = table(seq, mode); best = (1e99, None)
    for t in range(tries):
        x0 = rng.normal(size=2 * len(seq) * D)
        r = least_squares(resid, x0, args=(beta, tgt), method="trf", max_nfev=60)
        c = float(np.sqrt(np.mean(r.fun ** 2)))
        if c < best[0]: best = (c, r.x)
        print("   %s try %d: root-mean-square error %.3e" % (label, t, c), flush=True)
        if c < 1e-9: break
    return best
if seqs == "plain": seq = [1 << i for i in range(m)] * W
elif seqs == "all": seq = None
else: seq = [int(s) for s in seqs.split(",")]
t0 = time.time()
print("== m = %d, W = %d live, S = %d scratch, mode %s, sequence %s" % (m, W, S, mode, seqs), flush=True)
for r in range(restarts):
    sq = seq if seq is not None else list(rng.permutation(np.arange(1, 1 << m)))
    c, x = run(sq, mode, 1, "order %s" % ",".join(str(int(s)) for s in sq))
    if c < 1e-9 and mode == "pm":
        b2, t2 = table(sq, "all"); c2 = float(np.sqrt(np.mean(resid(x, b2, t2) ** 2)))
        print("   -> solves the +-1 characters; error on ALL characters with the same matrices: %.3e" % c2, flush=True)
        np.save("refl_m%d_W%d_S%d_%d.npy" % (m, W, S, r), np.concatenate([np.array(sq, dtype=float), x]))
print("   [%.0f s]" % (time.time() - t0))
