#!/usr/bin/env python3
"""gamma_floor.py [seconds per case]  -- what counting still says when address maps are allowed.   [h-2-clique17]
m = 5, W = 4.  An address map relabels the addresses inside a block of ONE array by an invertible bit matrix g.
Derived in h-2.md section 5: if G is the group generated by the address maps a unit uses, then for every quadratic form q
that is unchanged by G (q(g z) = q(z) for all z) the old-letter conditions hold word for word: counting, the clique lemma,
the zero-form lemma.  So:  floor(G) = fewest moves such that every G-invariant form with q(I) = 1 selects at least W.
This program computes floor(G) for a few groups G (integer programme, HiGHS; floating point; status 0 = proved optimal).
A small floor is NOT a unit; it says which address maps counting needs before it allows a saving.
"""
import sys, itertools
import numpy as np
from scipy.optimize import milp, LinearConstraint, Bounds
TL = float(sys.argv[1]) if len(sys.argv) > 1 else 30
m, W = 5, 4
V = list(range(1, 32))
def dot(a, b): return bin(a & b).count("1") & 1
pairs = [(i, j) for i in range(m) for j in range(i, m)]
mon = np.array([[(z >> i & 1) & (z >> j & 1) for z in V] for (i, j) in pairs], dtype=np.int64)
diag = [t for t, (i, j) in enumerate(pairs) if i == j]
Qs = np.arange(1, 1 << 15); bits = (Qs[:, None] >> np.arange(15)[None, :]) & 1
keep = bits[:, diag].sum(axis=1) % 2 == 1
A = (bits[keep] @ mon) % 2
def perm_of(f): return np.array([V.index(f(z)) for z in V])
def coordperm(p): return lambda z: sum(((z >> i) & 1) << p[i] for i in range(m))
def transv(a, b): return lambda z: z ^ (a if dot(b, z) else 0)          # z -> z + (b.z) a
def singer(z):                                                             # multiplication by x in GF(32), x^5 = x^2 + 1
    z <<= 1
    return (z ^ 0b100101) if z & 32 else z
cases = [
 ("no address map", []),
 ("one swap of two address bits", [coordperm([1, 0, 2, 3, 4])]),
 ("one map z -> z + (a.z) a, a = 01111 (orthogonal)", [transv(15, 15)]),
 ("two disjoint swaps at once", [coordperm([1, 0, 3, 2, 4])]),
 ("one 3-cycle of address bits", [coordperm([1, 2, 0, 3, 4])]),
 ("one 5-cycle of address bits", [coordperm([1, 2, 3, 4, 0])]),
 ("all permutations of 3 address bits", [coordperm([1, 0, 2, 3, 4]), coordperm([1, 2, 0, 3, 4])]),
 ("all 120 permutations of the address bits", [coordperm([1, 0, 2, 3, 4]), coordperm([1, 2, 3, 4, 0])]),
 ("the whole orthogonal group (720 maps)", [transv(a, a) for a in V if bin(a).count("1") % 2 == 0]),
 ("one shear: bit 2 added into bit 1 (not orthogonal)", [transv(1, 2)]),
 ("one map of order 31 (multiplication in the field of 32 elements)", [singer]),
]
print("m = 5, W = 4; plain 20 moves; without address maps counting allows 16 and the lemmas of h-2.md force 20")
for name, gens in cases:
    inv = np.ones(len(A), dtype=bool)
    for f in gens:
        p = perm_of(f)
        inv &= np.all(A[:, p] == A, axis=1)
    Ai = A[inv].astype(float)
    if len(Ai) == 0:
        print("  %-62s invariant forms with q(I)=1: 0 -> counting says nothing (floor 0)" % name, flush=True); continue
    res = milp(np.ones(31), constraints=[LinearConstraint(Ai, W, np.inf)], integrality=np.ones(31), bounds=Bounds(0, np.inf), options={"time_limit": TL})
    k = None if res.x is None else int(round(res.fun))
    sol = "" if res.x is None else " ".join("%s:%d" % (format(V[i], "05b"), int(round(res.x[i]))) for i in range(31) if round(res.x[i]))
    print("  %-62s invariant forms with q(I)=1: %5d of 16384; fewest moves %s (status %d, solver's lower bound %s)  e.g. %s"
          % (name, len(Ai), k, res.status, getattr(res, "mip_dual_bound", None), sol), flush=True)
