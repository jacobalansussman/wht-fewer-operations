#!/usr/bin/env python3
"""post.py K leaves.txt  -- every count vector with at most K moves that passes counting (m = 5, W = 4), up to the
orthogonal group of the 5-bit labels (720 maps, it contains the 120 coordinate permutations), and the clique test on each.
[h-2-clique17]   Exact integers.
Input: the leaves of cover.c (T, frozen mask, n_1..n_31).  Every feasible vector is a leaf plus extra moves on points that
are not frozen at that leaf.  Clique test (e2-2.md section 2): a form with q(I) = 1 is tight if it selects exactly W moves;
moves pairwise selected together by tight forms number at most W.  Copies of one direction are selected by the same forms.
"""
import sys, itertools
import numpy as np
K = int(sys.argv[1]); W = 4; m = 5
V = list(range(1, 32))
def dot(a, b): return bin(a & b).count("1") & 1
pairs = [(i, j) for i in range(m) for j in range(i, m)]
# forms with q(I) = 1 as 0/1 rows over the 31 points
mon = np.array([[(z >> i & 1) & (z >> j & 1) for z in V] for (i, j) in pairs], dtype=np.int64)
diag = [t for t, (i, j) in enumerate(pairs) if i == j]
Qs = np.arange(1, 1 << 15); bits = (Qs[:, None] >> np.arange(15)[None, :]) & 1
keep = bits[:, diag].sum(axis=1) % 2 == 1
A = (bits[keep] @ mon) % 2                      # 16384 x 31
assert A.shape == (16384, 31)
# the orthogonal group: generated by z -> z + (a.z) a, a of even weight
def tv(a): return tuple((z ^ a) if dot(a, z) else z for z in V)
gens = [tv(a) for a in V if bin(a).count("1") % 2 == 0]
idp = tuple(V); G = {idp}; frontier = [idp]
while frontier:
    new = []
    for g in frontier:
        for h in gens:
            c = tuple(h[g[i] - 1] for i in range(31))
            if c not in G: G.add(c); new.append(c)
    frontier = new
assert len(G) == 720, len(G)
P = np.array([[x - 1 for x in g] for g in G])   # P[g][i] = index of the image of point i
def canon(n):
    n = np.asarray(n); best = None
    for g in range(720):
        t = np.zeros(31, dtype=np.int64); t[P[g]] = n
        b = t.tobytes()
        if best is None or b < best[0]: best = (b, tuple(int(x) for x in t))
    return best[1]
def canon_fast(n):
    n = np.asarray(n, dtype=np.int64)
    T = np.zeros((720, 31), dtype=np.int64)
    np.put_along_axis(T, P, np.broadcast_to(n, (720, 31)), axis=1)
    order = np.lexsort(T.T[::-1]); return tuple(int(x) for x in T[order[0]])
def clique_test(n):
    n = np.asarray(n, dtype=np.int64); cnt = A @ n
    assert cnt.min() >= W, "not feasible"
    tight = np.unique(A[cnt == W] * (n > 0), axis=0)
    adj = [0] * 31; intight = 0
    for row in tight:
        s = [i for i in range(31) if row[i]]
        msk = sum(1 << i for i in s); intight |= msk
        for i in s: adj[i] |= msk & ~(1 << i)
    best = 0; bestset = 0
    def bk(R, wR, Pm, wP):
        nonlocal best, bestset
        if wR > best: best = wR; bestset = R
        if wR + wP <= best: return
        while Pm:
            v = Pm & -Pm; i = v.bit_length() - 1
            wP_i = sum(int(n[j]) for j in range(31) if (Pm & adj[i]) >> j & 1)
            bk(R | v, wR + int(n[i]), Pm & adj[i], wP_i)
            Pm &= ~v; wP -= int(n[i])
            if wR + wP <= best: return
    bk(0, 0, intight, sum(int(n[j]) for j in range(31) if intight >> j & 1))
    return len(tight), best, bestset
def fmt(n): return " ".join("%s:%d" % (format(V[i], "05b"), n[i]) for i in range(31) if n[i])
if __name__ == "__main__":
    classes = {}
    nleaf = 0
    for line in open(sys.argv[2]):
        p = line.split(); T = int(p[0]); fr = int(p[1]); n0 = list(map(int, p[2:])); nleaf += 1
        free = [i for i in range(31) if not fr >> i & 1]
        for e in range(0, K - T + 1):
            for comb in itertools.combinations_with_replacement(free, e):
                n = n0[:]
                for i in comb: n[i] += 1
                c = canon_fast(n)
                classes.setdefault(sum(c), set()).add(c)
    print("K = %d: %d leaves read" % (K, nleaf))
    odd = [i for i in range(31) if bin(V[i]).count("1") & 1]
    for tot in sorted(classes):
        cl = sorted(classes[tot]); surv = []; hist = {}
        nodesign = 0
        for c in cl:
            nt, best, bs = clique_test(c)
            hist[best] = hist.get(best, 0) + 1
            if best <= W: surv.append((c, nt, best))
        print("  %d moves: %d count vectors up to the 720 maps; largest joined set -> number of vectors: %s; NOT excluded by the clique lemma: %d"
              % (tot, len(cl), sorted(hist.items()), len(surv)))
        for c, nt, best in surv[:400]:
            print("     survivor (%d tight selections, largest joined set %d): %s" % (nt, best, fmt(c)))
