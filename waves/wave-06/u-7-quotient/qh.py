# u-7-quotient, run H: exact integers.  The rank-35 part of the 120 x 120 block, through symmetric 8 x 8 matrices.
# Roots doubled (integer coordinates): 56 lines with two entries +-2, 64 lines with eight entries +-1 (even number of minus signs).
# H1. M_E(i,j) = (-1)^(inner product of roots i, j in true scale): M_E^2 + 8 M_E - 128 = 0, trace 120 (same as the quadric block);
#     and M_E = 8 I + J - 2 (G o G), G the table of inner products, o = entry by entry.
# H2. the 64 x 28 sign matrix  (line of eight +-1, pair a<b) -> e_a e_b : columns pairwise orthogonal; the entry-by-entry products of
#     columns generate exactly 64 sign vectors (so the 28 columns are 28 columns of a 64-point transform); and which 28:
#     write the 64 generated vectors as a group (Z/2)^6, the 28 as the points with q = 1 of a quadratic form (checked: the set of
#     28 is not closed, the 35 others together with the unit are; and product of two of the 28 is in the 28 iff the pairs share a point).
import itertools
def norm(v):
    l = next(t for t in v if t); return v if l > 0 else tuple(-t for t in v)
roots = set()
for a, b in itertools.combinations(range(8), 2):
    for sa in (2, -2):
        for sb in (2, -2):
            v = [0] * 8; v[a] = sa; v[b] = sb; roots.add(tuple(v))
for s in itertools.product((1, -1), repeat=8):
    if sum(1 for t in s if t < 0) % 2 == 0: roots.add(tuple(s))
lines = sorted({norm(r) for r in roots}); n = len(lines); assert n == 120
G = [[sum(a * b for a, b in zip(u, v)) // 4 for v in lines] for u in lines]     # true inner products: 2 on the diagonal, 0, +-1
assert {G[i][j] for i in range(n) for j in range(n) if i != j} == {0, 1, -1}
M = [[(-1) ** (G[i][j] % 2) for j in range(n)] for i in range(n)]
ok1 = all(sum(M[i][t] * M[t][j] for t in range(n)) + 8 * M[i][j] - 128 * (i == j) == 0 for i in range(n) for j in range(n))
ok2 = all(M[i][j] == 8 * (i == j) + 1 - 2 * G[i][j] ** 2 for i in range(n) for j in range(n))
print('H1. M_E^2 + 8 M_E - 128 = 0: %s ; trace %d ; M_E = 8 I + J - 2 (G o G): %s' % (ok1, sum(M[i][i] for i in range(n)), ok2))
spin = [l for l in lines if all(abs(t) == 1 for t in l)]; assert len(spin) == 64
pairs = list(itertools.combinations(range(8), 2))
cols = {p: tuple(l[p[0]] * l[p[1]] for l in spin) for p in pairs}
orth = all(sum(x * y for x, y in zip(cols[p], cols[q])) == 0 for p in pairs for q in pairs if p != q)
grp = {tuple([1] * 64)}
frontier = list(grp)
while frontier:
    g = frontier.pop()
    for p in pairs:
        h = tuple(x * y for x, y in zip(g, cols[p]))
        if h not in grp: grp.add(h); frontier.append(h)
c28 = set(cols.values())
share = all((tuple(x * y for x, y in zip(cols[p], cols[q])) in c28) == (len(set(p) & set(q)) == 1) for p in pairs for q in pairs if p != q)
rest = grp - c28
closed = all(tuple(x * y for x, y in zip(g, h)) in grp for g in list(rest)[:8] for h in rest)
print('H2. 64 x 28 matrix: columns pairwise orthogonal: %s ; group generated by the columns has %d elements ; distinct columns %d ;' % (orth, len(grp), len(c28)))
print('    product of two columns is again one of the 28 exactly when the two pairs share one point: %s' % share)
print('    so the 28 columns are 28 of the 64 characters of a group of 64 elements: a 64 x 28 block of the 64-point transform (rows relabelled by an address map)')
